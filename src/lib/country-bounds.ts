/** Whole world, for when the country is unknown or unlisted. */
export const WORLD_BOUNDS: [number, number, number, number] = [-170, -58, 179, 74];

export function boundsForCountry(code: string | null): {
  bounds: [number, number, number, number];
  country: string | null;
} {
  if (!code) return { bounds: WORLD_BOUNDS, country: null };
  const upper = code.toUpperCase();
  const bounds = COUNTRY_BOUNDS[upper];
  return bounds ? { bounds, country: upper } : { bounds: WORLD_BOUNDS, country: null };
}
